#!/usr/bin/env python3
"""Generate src/curve_table.h: the perceptual dimming curve.

Maps the 256 brightness levels to 12-bit PSC duty values. Level 0 is off; levels
1-255 are spaced evenly in CIE 1931 lightness (L*) between the shortest pulse the
output stage switches cleanly (--min-duty) and full on (--top).
"""

import argparse

LEVELS = 256


def cie_luminance(lightness: float) -> float:
    """Relative luminance (0-1) for a CIE lightness L* (0-100)."""
    if lightness <= 8.0:
        return lightness / 903.3
    return ((lightness + 16.0) / 116.0) ** 3


def build_table(top: int, min_duty: int) -> list[int]:
    table = [0]
    for level in range(1, LEVELS):
        luminance = cie_luminance(100.0 * level / (LEVELS - 1))
        table.append(round(min_duty + (top - min_duty) * luminance))
    return table


def check_table(table: list[int]) -> None:
    steps = [b - a for a, b in zip(table[1:], table[2:])]
    if min(steps) < 0:
        raise SystemExit("curve is not monotonic")
    # curve_duty() interpolates with a 16-bit product of step and fraction
    if max(steps) * 255 > 0xFFFF:
        raise SystemExit("curve step too large for 16-bit interpolation")


def render(table: list[int], top: int, min_duty: int) -> str:
    rows = []
    for start in range(0, LEVELS, 8):
        rows.append("    " + ", ".join(f"{v:4d}" for v in table[start:start + 8]) + ",")
    body = "\n".join(rows)
    return f"""/* Generated by tools/gen_curve.py --top {top} --min-duty {min_duty}; do not edit. */
#ifndef CURVE_TABLE_H
#define CURVE_TABLE_H

#define CURVE_TOP {top}u
#define CURVE_MIN_DUTY {min_duty}u

/* PSC duty per level, CIE lightness spacing */
static const uint16_t curve_table[{LEVELS}] CURVE_PROGMEM = {{
{body}
}};

#endif
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--top", type=int, default=4095, help="PSC period top value")
    parser.add_argument("--min-duty", type=int, default=20,
                        help="duty of level 1, in PSC clocks")
    args = parser.parse_args()
    table = build_table(args.top, args.min_duty)
    check_table(table)
    print(render(table, args.top, args.min_duty), end="")


if __name__ == "__main__":
    main()
